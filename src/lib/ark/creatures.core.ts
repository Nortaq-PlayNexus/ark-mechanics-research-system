import { BUFF_BY_SLUG } from "./buffs";
import type { AbilityKind, ArkAbility, ArkCreature, Confidence } from "./types";

/**
 * Creature knowledge base — part 1 (apex predators, raiders, boss meta).
 *
 * baseHp / baseMelee / baseWeight are approximate published base values used for
 * triage only. baseSpeed is an ARK OMNISCIENCE relative mobility index (1-100),
 * NOT an in-game number. `profile` is an analyst rating (0-100).
 */

export type CreatureInput = Omit<Partial<ArkCreature>, "abilities"> & {
  slug: string;
  name: string;
  species: string;
  profile: ArkCreature["profile"];
  notes: string;
  /** hand-written abilities that cannot be derived from buff links */
  extraAbilities?: ArkAbility[];
};

/**
 * Abilities are derived: every granted buff becomes an ability entry, immunities
 * and weight reductions become passive entries, and a standard melee attack is
 * always present. This keeps the KB free of duplicated hand-typed data.
 */
function deriveAbilities(
  input: Omit<CreatureInput, "extraAbilities">,
  extras: ArkAbility[] = [],
): ArkAbility[] {
  const list: ArkAbility[] = [
    ab("Bite / Melee", "primary", "Standard melee attack; damage scales with melee stat points and saddles do not add damage."),
  ];
  for (const buffSlug of input.grants ?? []) {
    const buff = BUFF_BY_SLUG.get(buffSlug);
    if (!buff) continue;
    list.push(
      ab(buff.name, buff.kind === "debuff" ? "special" : "active", buff.notes, {
        grants: [buffSlug],
        tags: [buff.category, buff.scope],
        confidence: buff.confidence,
        documented: buff.confidence !== "needs-verification",
      }),
    );
  }
  for (const imm of input.immune ?? []) {
    const buff = BUFF_BY_SLUG.get(imm);
    list.push(
      ab(`Immunity: ${buff?.name ?? imm}`, "passive", `Ignores the ${buff?.name ?? imm} effect.`, {
        tags: ["immunity"],
        confidence: "documented",
      }),
    );
  }
  for (const wr of input.weightReductions ?? []) {
    list.push(
      ab(`${wr.resource} weight reduction`, "passive", `Carries ${wr.resource} at a reduced encumbrance (~${wr.pct}%).`, {
        tags: ["weight"],
      }),
    );
  }
  return [...list, ...extras];
}

export const CREATURE_DEFAULTS: Omit<ArkCreature, "slug" | "name" | "species" | "profile" | "abilities" | "notes"> = {
  diet: "carnivore",
  temperament: "aggressive",
  tier: "large",
  rideable: true,
  baseHp: 0,
  baseMelee: 0,
  baseWeight: 0,
  baseSpeed: 40,
  roles: [],
  tags: [],
  maps: ["island", "scorched", "ragnarok", "valguero", "crystal-isles", "genesis", "extinction"],
  grants: [],
  affectedBy: [],
  immune: [],
  counters: [],
  confidence: "documented",
  sources: [],
};

export function makeCreature(input: CreatureInput): ArkCreature {
  const { extraAbilities = [], ...rest } = input;
  return {
    ...CREATURE_DEFAULTS,
    ...rest,
    abilities: deriveAbilities(rest, extraAbilities),
  };
}

export function ab(
  name: string,
  kind: AbilityKind,
  description: string,
  extra: { grants?: string[]; tags?: string[]; confidence?: Confidence; documented?: boolean } = {},
): ArkAbility {
  return { name, kind, description, documented: true, confidence: "documented", ...extra };
}

